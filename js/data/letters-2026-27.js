// Bolles 2026-27 letter days, transcribed from the official Middle School
// (Bartram) and Upper School (San Jose) student planners.
//
// Letter days are stored per date instead of computed because the official
// calendar does not always follow the rotation (Upper School skips the G day
// on Dec 14 for exams, Middle School does not). Entries are 'MM-DD' + letter;
// Aug-Dec are 2026 and Jan-Jul are 2027.

const year = (mmdd) => (Number(mmdd.slice(0, 2)) >= 7 ? 2026 : 2027);
const expand = (months) =>
  Object.fromEntries(
    months
      .join(' ')
      .split(/\s+/)
      .filter(Boolean)
      .map((s) => [`${year(s)}-${s.slice(0, 5)}`, s.slice(5)]),
  );

